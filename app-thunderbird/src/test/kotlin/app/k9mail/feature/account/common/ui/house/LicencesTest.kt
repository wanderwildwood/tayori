package app.k9mail.feature.account.common.ui.house

import java.io.File
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * The Licenses page's data as the build made it: the AboutLibraries plugin, applied in this app
 * module, writes build/generated/aboutLibraries/<variant>/res/raw/aboutlibraries.json before the
 * unit tests compile. The screen and the family texts live in feature/account/common.
 */
class LicencesTest {
    private val json: File? = File("build/generated/aboutLibraries").walkTopDown()
        .filter { it.name == "aboutlibraries.json" }
        .sortedBy { if ("release" in it.path.lowercase()) 0 else 1 }
        .firstOrNull()

    private val generated by lazy { licenceComponentsFromJson(json!!.readText()) }

    private val data by lazy {
        LicencesData(
            "tayori", SOURCE_URL, "GPL-3.0-only", generated,
            LICENCE_RAW.map { LicenceText(it.first, it.first, it.second) }, emptyList(),
        )
    }

    /** What must be on the page whatever else changes: group:artifact, or a config/libraries name. */
    private val EXPECTED = listOf<String>(
        "com.squareup.okhttp3:okhttp", "com.squareup.okio:okio", "com.squareup.moshi:moshi",
        "org.jsoup:jsoup", "com.jcraft:jzlib", "com.beetstra.jutf7:jutf7", "com.github.bumptech.glide:glide",
        "org.apache.james:apache-mime4j-core", "commons-io:commons-io", "com.jakewharton.timber:timber",
        "androidx.datastore:datastore-preferences-external-protobuf", "com.mudita:MMD",
        "Lato typeface", "Material Symbols icons", "Thunderbird for Android and K-9 Mail",
    )

    @Test fun theBuildListedTheLibraries() {
        assertNotNull("no generated aboutlibraries.json: is the AboutLibraries plugin applied?", json)
        assertTrue(generated.size >= 5)
    }

    @Test fun theDataHasNoProblems() {
        assertEquals(emptyList<String>(), licencesProblems(data))
    }

    @Test fun everyExpectedComponentIsListed() {
        val missing = EXPECTED.filterNot { id -> generated.any { it.note?.startsWith("$id ") == true || it.name == id } }
        assertEquals(emptyList<String>(), missing)
    }

    @Test fun mmdIsShownAsMudita() {
        assertEquals("Mudita", generated.first { it.note?.startsWith("com.mudita:MMD ") == true }.author)
    }

    @Test fun debugOnlyLibrariesAreNotListed() {
        val debugOnly = listOf("androidx.glance:glance-preview", "org.jetbrains.kotlin:kotlin-reflect")
        assertEquals(emptyList<String>(), generated.filter { c -> debugOnly.any { c.note?.startsWith("$it ") == true } })
    }

    @Test fun theSourceLinkIsTheRepo() {
        assertEquals("https://github.com/wanderwildwood/tayori", SOURCE_URL)
    }

    @Test fun gplIsFirstAndEveryTextIsBundled() {
        assertEquals("gpl", orderedTexts(data.texts).first().id)
        val raw = File("../feature/account/common/src/main/res/raw")
        assertTrue(raw.listFiles().orEmpty().count { it.extension == "txt" } >= LICENCE_RAW.size)
        assertTrue(licenceParagraphs(File(raw, raw.list().orEmpty().first { it.contains("gpl") }).readText()).size > 10)
    }
}
